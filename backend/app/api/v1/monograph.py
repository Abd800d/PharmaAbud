"""Monograph content endpoints (§6, §25, §90).

Full editing of drug monograph child sections: indications, contraindications,
warnings, precautions, side effects, interactions, food interactions, dosages,
pregnancy, lactation, administration, monitoring, overdose, therapeutic
alternatives, plus field-level source links (§25).

Every write requires drug.edit, bumps record_version and writes an audit entry.
Dose content is NEVER generated by the platform — clients submit text that
must come from a verified source (or the explicit
"Not available / Requires verified source" placeholder).
"""
