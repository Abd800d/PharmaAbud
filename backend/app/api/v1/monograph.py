# ------------------------------------------------------------------ helpers
def _get_drug(db: Session, drug_id: str) -> Drug:
    drug = db.get(Drug, drug_id)
    if drug is None:
        raise NotFoundError("Drug", drug_id)
    return drug


def _bump(db: Session, drug: Drug, user: User, request: Request, action: str, payload) -> None:
    drug.updated_by = user.id
    drug.record_version = (drug.record_version or 1) + 1
    record_audit(
        db,
        action=action,
        entity_type="drug",
        entity_id=drug.id,
        user_id=user.id,
        new_value=payload,
        ip_address=request.client.host if request.client else "",
    )
    db.flush()


def _replace(db: Session, model, drug_id: str, items, defaults: dict | None = None) -> int:
    """Replace all rows of a child section (ordered list semantics)."""
    for row in db.scalars(select(model).where(model.drug_id == drug_id)).all():
        db.delete(row)
    db.flush()
    count = 0
    for i, item in enumerate(items):
        data = item.model_dump() if hasattr(item, "model_dump") else dict(item)
        data.setdefault("sort_order", i)
        db.add(model(drug_id=drug_id, **(defaults or {}), **data))
        count += 1
    db.flush()
    return count


