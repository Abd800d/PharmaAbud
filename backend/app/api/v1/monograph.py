@router.put("/{drug_id}/indications", response_model=Message,
            dependencies=[Depends(require_permission("drug.edit"))])
def set_indications(drug_id: str, payload: IndicationList, request: Request,
                    db: Session = Depends(get_db), user: User = Depends(get_current_user)) -> Message:
    drug = _get_drug(db, drug_id)
    n = _replace(db, DrugIndication, drug_id, payload.items)
    _bump(db, drug, user, request, "drug.indications.updated", {"count": n})
    return Message(message=f"Indications updated ({n}).")


